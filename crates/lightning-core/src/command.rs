//! Command declaration and registration.
//!
//! A [`Command`] is a *static* (const-friendly) description of a command: name,
//! description, options and a pointer to the handler. That is what makes
//! automatic registration with `inventory` possible without hand-written lists.

use std::sync::Arc;

use crate::{BoxFuture, Context, Middleware, Reply, Result};

/// Where a command can run.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum CommandKind {
    /// Only as a slash command (`/ping`).
    Slash,
    /// Only as a prefix command (`!ping`).
    Prefix,
    /// On both surfaces. **This is the default.**
    Both,
}

impl CommandKind {
    /// `true` if this configuration allows the given surface.
    pub const fn allows(self, slash: bool) -> bool {
        match self {
            Self::Slash => slash,
            Self::Prefix => !slash,
            Self::Both => true,
        }
    }
}

/// Handler signature generated by `#[command]`.
pub type RunFn = for<'a> fn(&'a Context) -> BoxFuture<'a, Result<Reply>>;

/// Middleware factory declared on a command.
///
/// It runs **once at startup**, so layers such as [`crate::Cooldown`] keep shared
/// state across invocations.
pub type LayerFn = fn() -> Vec<Arc<dyn Middleware>>;

/// Full description of a command.
///
/// You normally do not build this by hand: `#[lightning::command]` generates it.
#[derive(Clone)]
pub struct Command {
    /// Name without the prefix (`ping`).
    pub name: &'static str,
    /// Description shown by Discord.
    pub description: &'static str,
    /// Surfaces where the command can be used.
    pub kind: CommandKind,
    /// Declared options (generated from `Args<T>`).
    pub options: &'static [crate::OptionSpec],
    /// Aliases for prefix commands.
    pub aliases: &'static [&'static str],
    /// Whether it can only be used in guilds.
    pub guild_only: bool,
    /// Whether it is marked as NSFW in Discord.
    pub nsfw: bool,
    /// Default permissions (raw `Permissions` bits).
    pub default_permissions: Option<u64>,
    run: Option<RunFn>,
    layers: Option<LayerFn>,
}

impl std::fmt::Debug for Command {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.debug_struct("Command")
            .field("name", &self.name)
            .field("kind", &self.kind)
            .field("options", &self.options.len())
            .finish_non_exhaustive()
    }
}

impl Command {
    /// Creates an empty command. Intended for the macros.
    #[doc(hidden)]
    pub const fn new(name: &'static str, description: &'static str) -> Self {
        Self {
            name,
            description,
            kind: CommandKind::Both,
            options: &[],
            aliases: &[],
            guild_only: false,
            nsfw: false,
            default_permissions: None,
            run: None,
            layers: None,
        }
    }

    /// Changes the description.
    pub const fn description(mut self, description: &'static str) -> Self {
        self.description = description;
        self
    }

    /// Changes the allowed surfaces.
    pub const fn kind(mut self, kind: CommandKind) -> Self {
        self.kind = kind;
        self
    }

    /// Declares the options (generated by `derive(CommandArgs)`).
    pub const fn options(mut self, options: &'static [crate::OptionSpec]) -> Self {
        self.options = options;
        self
    }

    /// Declares prefix aliases.
    pub const fn aliases(mut self, aliases: &'static [&'static str]) -> Self {
        self.aliases = aliases;
        self
    }

    /// Restricts the command to guilds.
    pub const fn guild_only(mut self) -> Self {
        self.guild_only = true;
        self
    }

    /// Marks the command as NSFW.
    pub const fn nsfw(mut self) -> Self {
        self.nsfw = true;
        self
    }

    /// Default permissions (raw Discord bits).
    pub const fn permissions(mut self, bits: u64) -> Self {
        self.default_permissions = Some(bits);
        self
    }

    /// Attaches the handler. Used by `#[command]`.
    #[doc(hidden)]
    pub const fn handler(mut self, run: RunFn) -> Self {
        self.run = Some(run);
        self
    }

    /// Attaches the middleware factory. Used by `#[command]`.
    #[doc(hidden)]
    pub const fn layers(mut self, layers: LayerFn) -> Self {
        self.layers = Some(layers);
        self
    }

    /// The attached handler, if any.
    pub fn run(&self) -> Option<RunFn> {
        self.run
    }

    /// Builds this command's middleware layers.
    pub fn build_layers(&self) -> Vec<Arc<dyn Middleware>> {
        self.layers.map(|factory| factory()).unwrap_or_default()
    }

    /// `true` if the command is called (or aliased) by `name`.
    pub fn matches(&self, name: &str) -> bool {
        self.name == name || self.aliases.contains(&name)
    }
}

inventory::collect!(Command);
