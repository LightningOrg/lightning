//! Typed command arguments.
//!
//! Declare a `struct` with `#[derive(CommandArgs)]` and ask for it as `Args<T>`.
//! Lightning generates Discord options **and** the prefix parser from the same
//! fields: a single source of truth for both `/echo` and `!echo`.

use std::ops::{Deref, DerefMut};

use serde_json::{Map, Value};
use twilight_model::id::Id;

use crate::error::{Error, Result};

/// Type of a Discord option.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum OptionKind {
    /// Text.
    String,
    /// 64-bit integer.
    Integer,
    /// Decimal number.
    Number,
    /// Boolean.
    Boolean,
}

impl OptionKind {
    /// Numeric code used by the Discord API.
    pub const fn code(self) -> u8 {
        match self {
            Self::String => 3,
            Self::Integer => 4,
            Self::Boolean => 5,
            Self::Number => 10,
        }
    }
}

/// Option metadata, generated by `#[derive(CommandArgs)]`.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct OptionSpec {
    /// Option name (lowercase, no spaces).
    pub name: &'static str,
    /// Description shown by Discord.
    pub description: &'static str,
    /// Option type.
    pub kind: OptionKind,
    /// Whether it is required.
    pub required: bool,
}

/// A set of typed arguments.
///
/// `#[derive(CommandArgs)]` implements it; you can also implement it by hand if
/// you need something exotic.
pub trait CommandArgs: Sized + Send + 'static {
    /// Options published to Discord.
    const OPTIONS: &'static [OptionSpec];

    /// Builds the value from interaction options.
    ///
    /// # Errors
    ///
    /// Returns an error if a required field is missing or the type does not fit.
    fn from_options(options: Map<String, Value>) -> Result<Self>;

    /// Builds the value from prefix command tokens.
    ///
    /// # Errors
    ///
    /// Returns an error if a required token is missing or cannot be converted.
    fn from_prefix(tokens: &[String]) -> Result<Self>;
}

/// Wraps a handler's arguments: `Args<MyStruct>`.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub struct Args<T>(pub T);

impl<T> Args<T> {
    /// Unwraps the arguments.
    pub fn into_inner(self) -> T {
        self.0
    }
}

impl<T> Deref for Args<T> {
    type Target = T;

    fn deref(&self) -> &Self::Target {
        &self.0
    }
}

impl<T> DerefMut for Args<T> {
    fn deref_mut(&mut self) -> &mut Self::Target {
        &mut self.0
    }
}

impl<T> From<T> for Args<T> {
    fn from(value: T) -> Self {
        Self(value)
    }
}

impl CommandArgs for () {
    const OPTIONS: &'static [OptionSpec] = &[];

    fn from_options(_: Map<String, Value>) -> Result<Self> {
        Ok(())
    }

    fn from_prefix(_: &[String]) -> Result<Self> {
        Ok(())
    }
}

/// Macro helper: missing required argument error.
#[doc(hidden)]
pub fn missing(name: &str) -> Error {
    Error::MissingArgument(name.to_owned())
}

/// Macro helper: conversion error.
#[doc(hidden)]
pub fn invalid(name: &str, reason: impl std::fmt::Display) -> Error {
    Error::InvalidArgument {
        name: name.to_owned(),
        reason: reason.to_string(),
    }
}

/// Conversion from the JSON `Value` delivered by an interaction.
///
/// Used by `#[derive(CommandArgs)]`; you rarely implement it by hand.
pub trait FromOptionValue: Sized {
    /// Converts the value; `name` is used for error messages.
    fn from_option(value: Value, name: &'static str) -> Result<Self>;
}

/// Conversion from a prefix command token.
///
/// Used by `#[derive(CommandArgs)]`; you rarely implement it by hand.
pub trait FromToken: Sized {
    /// Converts the token; `name` is used for error messages.
    fn from_token(token: &str, name: &'static str) -> Result<Self>;
}

impl FromOptionValue for Value {
    fn from_option(value: Value, _: &'static str) -> Result<Self> {
        Ok(value)
    }
}

impl FromOptionValue for String {
    fn from_option(value: Value, name: &'static str) -> Result<Self> {
        match value {
            Value::String(text) => Ok(text),
            Value::Number(number) => Ok(number.to_string()),
            Value::Bool(flag) => Ok(flag.to_string()),
            Value::Null => Err(missing(name)),
            other => Err(invalid(name, format!("expected a string, got {other}"))),
        }
    }
}

impl FromToken for String {
    fn from_token(token: &str, _: &'static str) -> Result<Self> {
        Ok(token.to_owned())
    }
}

impl<T: FromOptionValue> FromOptionValue for Option<T> {
    fn from_option(value: Value, name: &'static str) -> Result<Self> {
        match value {
            Value::Null => Ok(None),
            other => T::from_option(other, name).map(Some),
        }
    }
}

impl<T: FromOptionValue> FromOptionValue for Vec<T> {
    fn from_option(value: Value, name: &'static str) -> Result<Self> {
        match value {
            Value::Array(values) => values
                .into_iter()
                .map(|value| T::from_option(value, name))
                .collect(),
            Value::Null => Err(missing(name)),
            other => Ok(vec![T::from_option(other, name)?]),
        }
    }
}

impl<T> FromOptionValue for Id<T> {
    fn from_option(value: Value, name: &'static str) -> Result<Self> {
        let raw = match value {
            Value::Number(number) => number
                .as_u64()
                .ok_or_else(|| invalid(name, "id out of range"))?,
            Value::String(text) => text.parse().map_err(|error| invalid(name, error))?,
            Value::Null => return Err(missing(name)),
            other => return Err(invalid(name, format!("expected an id, got {other}"))),
        };

        Ok(Id::new(raw))
    }
}

impl<T> FromToken for Id<T> {
    fn from_token(token: &str, name: &'static str) -> Result<Self> {
        let raw = token.parse().map_err(|error| invalid(name, error))?;

        Ok(Id::new(raw))
    }
}

impl FromOptionValue for bool {
    fn from_option(value: Value, name: &'static str) -> Result<Self> {
        match value {
            Value::Bool(flag) => Ok(flag),
            Value::String(text) => parse_bool(&text, name),
            Value::Number(number) => Ok(number.as_u64().unwrap_or(0) != 0),
            Value::Null => Err(missing(name)),
            other => Err(invalid(name, format!("expected a boolean, got {other}"))),
        }
    }
}

impl FromToken for bool {
    fn from_token(token: &str, name: &'static str) -> Result<Self> {
        parse_bool(token, name)
    }
}

impl FromOptionValue for char {
    fn from_option(value: Value, name: &'static str) -> Result<Self> {
        let text = String::from_option(value, name)?;
        single_char(&text, name)
    }
}

impl FromToken for char {
    fn from_token(token: &str, name: &'static str) -> Result<Self> {
        single_char(token, name)
    }
}

fn parse_bool(text: &str, name: &'static str) -> Result<bool> {
    match text.to_ascii_lowercase().as_str() {
        "true" | "1" | "yes" | "on" => Ok(true),
        "false" | "0" | "no" | "off" => Ok(false),
        _ => Err(invalid(name, "expected true or false")),
    }
}

fn single_char(text: &str, name: &'static str) -> Result<char> {
    let mut chars = text.chars();
    match (chars.next(), chars.next()) {
        (Some(character), None) => Ok(character),
        _ => Err(invalid(name, "expected a single character")),
    }
}

macro_rules! impl_number {
    ($($ty:ty),* $(,)?) => {
        $(
            impl FromOptionValue for $ty {
                fn from_option(value: Value, name: &'static str) -> Result<Self> {
                    match value {
                        Value::Number(number) => number
                            .to_string()
                            .parse()
                            .map_err(|error| invalid(name, error)),
                        Value::String(text) => text
                            .parse()
                            .map_err(|error| invalid(name, error)),
                        Value::Null => Err(missing(name)),
                        other => Err(invalid(name, format!("expected a number, got {other}"))),
                    }
                }
            }

            impl FromToken for $ty {
                fn from_token(token: &str, name: &'static str) -> Result<Self> {
                    token.parse().map_err(|error| invalid(name, error))
                }
            }
        )*
    };
}

impl_number!(
    i8, i16, i32, i64, i128, isize, u8, u16, u32, u64, u128, usize, f32, f64
);
