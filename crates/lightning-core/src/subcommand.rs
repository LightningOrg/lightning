//! Subcommands and subcommand groups.
//!
//! A [`Subcommand`] is a command that lives inside another one:
//!
//! ```ignore
//! use lightning::prelude::*;
//!
//! /// Manage the bot configuration
//! #[command]
//! async fn config() {}
//!
//! /// Show the current configuration
//! #[subcommand(command = "config")]
//! async fn show() -> Reply {
//!     Reply::text("everything is fine")
//! }
//!
//! /// Change a setting
//! #[subcommand(command = "config", group = "set", group_description = "Change a setting")]
//! async fn channel(ctx: Context) -> Reply {
//!     Reply::text("setting updated")
//! }
//! ```
//!
//! Discord requires the parent to be a normal command. Its options become the
//! subcommands (and groups) instead of scalar options; the parent handler is
//! only used as a prefix fallback (`!config`). Slash users always pick a
//! subcommand.
//!
//! [`Subcommand`] entries are static and registered with `inventory`, just like
//! [`crate::Command`].

use std::sync::Arc;

use crate::command::{LayerFn, RunFn};
use crate::{Middleware, OptionSpec};

/// A subcommand (optionally inside a group) attached to a parent command.
///
/// You normally do not build this by hand: `#[lightning::subcommand]`
/// generates it and `inventory` registers it automatically.
#[derive(Clone)]
pub struct Subcommand {
    /// Parent command name, without the slash (`config`).
    pub command: &'static str,
    /// Optional group name, without the slash (`set`).
    pub group: Option<&'static str>,
    /// Description of the group shown by Discord.
    ///
    /// Empty for subcommands without a group.
    pub group_description: &'static str,
    /// Subcommand name, without the slash (`channel`).
    pub name: &'static str,
    /// Description shown by Discord.
    pub description: &'static str,
    /// Declared options (generated from `Args<T>`).
    pub options: &'static [OptionSpec],
    /// Aliases for prefix commands.
    pub aliases: &'static [&'static str],
    run: Option<RunFn>,
    layers: Option<LayerFn>,
}

impl std::fmt::Debug for Subcommand {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.debug_struct("Subcommand")
            .field("command", &self.command)
            .field("group", &self.group)
            .field("name", &self.name)
            .field("options", &self.options.len())
            .finish_non_exhaustive()
    }
}

impl Subcommand {
    /// Creates an empty subcommand. Intended for the macros.
    #[doc(hidden)]
    pub const fn new(command: &'static str, name: &'static str, description: &'static str) -> Self {
        Self {
            command,
            group: None,
            group_description: "",
            name,
            description,
            options: &[],
            aliases: &[],
            run: None,
            layers: None,
        }
    }

    /// Places the subcommand inside a group.
    pub const fn group(mut self, group: &'static str, description: &'static str) -> Self {
        self.group = Some(group);
        self.group_description = description;
        self
    }

    /// Declares the options (generated by `derive(CommandArgs)`).
    pub const fn options(mut self, options: &'static [OptionSpec]) -> Self {
        self.options = options;
        self
    }

    /// Declares prefix aliases.
    pub const fn aliases(mut self, aliases: &'static [&'static str]) -> Self {
        self.aliases = aliases;
        self
    }

    /// Attaches the handler. Used by `#[subcommand]`.
    #[doc(hidden)]
    pub const fn handler(mut self, run: RunFn) -> Self {
        self.run = Some(run);
        self
    }

    /// Attaches the middleware factory. Used by `#[subcommand]`.
    #[doc(hidden)]
    pub const fn layers(mut self, layers: LayerFn) -> Self {
        self.layers = Some(layers);
        self
    }

    /// The attached handler, if any.
    pub fn run(&self) -> Option<RunFn> {
        self.run
    }

    /// Builds this subcommand's middleware layers.
    pub fn build_layers(&self) -> Vec<Arc<dyn Middleware>> {
        self.layers.map(|factory| factory()).unwrap_or_default()
    }

    /// `true` if this subcommand belongs to `command` and is called (or
    /// aliased) by `name` inside `group`.
    pub fn matches(&self, command: &str, group: Option<&str>, name: &str) -> bool {
        self.command == command
            && self.group == group
            && (self.name == name || self.aliases.contains(&name))
    }
}

inventory::collect!(Subcommand);
