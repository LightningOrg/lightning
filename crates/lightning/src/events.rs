//! Event and component handlers, registered with `inventory`.

use std::sync::Arc;

use lightning_core::command::RunFn;
use lightning_core::{BoxFuture, StateMap};
use twilight_gateway::Event;
use twilight_http::Client;
use twilight_model::id::Id;
use twilight_model::id::marker::ApplicationMarker;

use crate::voice::Voice;
use crate::voice_states::VoiceStates;

/// Access to runtime services from inside an event handler.
#[derive(Clone)]
pub struct EventContext {
    /// Authenticated HTTP client.
    pub http: Arc<Client>,
    /// Application id.
    pub application_id: Id<ApplicationMarker>,
    /// State injected with `.state(...)`.
    pub state: Arc<StateMap>,
    /// Shard that received the event.
    pub shard_id: u32,
    /// Voice subsystem (join, leave, play, moderation).
    pub voice: Voice,
    /// Live voice-state cache.
    pub voice_states: VoiceStates,
}

impl std::fmt::Debug for EventContext {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.debug_struct("EventContext")
            .field("application_id", &self.application_id)
            .field("shard_id", &self.shard_id)
            .field("voice", &self.voice)
            .finish_non_exhaustive()
    }
}

impl EventContext {
    /// Retrieves an injected state.
    pub fn state<T: Send + Sync + 'static>(&self) -> Option<Arc<T>> {
        self.state.get::<T>()
    }
}

/// Gateway event handler, generated by `#[event]`.
#[doc(hidden)]
pub struct EventHandler {
    /// Event name (informational).
    pub name: &'static str,
    /// Function that filters and runs the handler.
    pub handle: for<'a> fn(&'a Event, EventContext) -> BoxFuture<'a, ()>,
}

/// Interactive component handler, generated by `#[component]`.
#[doc(hidden)]
pub struct ComponentHandler {
    /// `custom_id` prefix it handles.
    pub id: &'static str,
    /// Handler.
    pub run: RunFn,
}

inventory::collect!(EventHandler);
inventory::collect!(ComponentHandler);
